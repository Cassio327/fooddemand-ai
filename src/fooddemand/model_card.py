from __future__ import annotations

import json
from pathlib import Path


def render_model_card(report: dict) -> str:
    aggregate = report.get("backtest", {}).get("aggregate", {})
    model = aggregate.get("model", report.get("holdout", {}).get("model", {}))
    baseline = aggregate.get("seasonal_naive", report.get("holdout", {}).get("seasonal_naive", {}))

    def metric(block: dict, key: str) -> str:
        value = block.get(key)
        return "not run" if value is None else f"{value:.4f}"

    return f"""---
library_name: scikit-learn
tags:
- time-series
- forecasting
- retail
- demand-forecasting
- tabular-regression
---

# FoodDemand AI

Retail demand forecasting model. Dataset provenance: **{report.get('data_source', 'unverified')}**.

**Important:** synthetic/unverified scores are demonstration-only and must not be
advertised as real Kaggle performance.

## Intended use

Educational and portfolio demonstration of an end-to-end ML forecasting workflow. It is not a
production inventory planning system and should not be used for financial or operational decisions
without additional validation, monitoring and business constraints.

## Evaluation

Evaluation uses chronological splits. Historical target features are shifted before use.

| Metric | Seasonal naive | ML model |
| --- | ---: | ---: |
| RMSLE | {metric(baseline, 'rmsle')} | {metric(model, 'rmsle')} |
| MAE | {metric(baseline, 'mae')} | {metric(model, 'mae')} |
| WAPE | {metric(baseline, 'wape')} | {metric(model, 'wape')} |

Numbers are generated by the repository training pipeline. If they show `not run`, the official
dataset has not yet been executed in that checkout.

## Model inputs

The model combines calendar variables, promotion count, store metadata, lagged demand, lagged oil
price, lagged transactions and a national-holiday indicator. Missing auxiliary tables are supported
and imputed by the pipeline.

## Limitations

- Backtesting is rolling one-step evaluation: validation rows may use actual earlier observations.
- A recursive fixed-horizon production forecast would require forecasting future lag values.
- Store Sales is an Ecuadorian grocery dataset and does not represent iFood data.
- External shocks, stockouts and unseen product families can reduce accuracy.
- The artifact is for demonstration and requires monitoring before production use.
"""


def write_model_card(report_path: str | Path, output_path: str | Path) -> None:
    report = json.loads(Path(report_path).read_text(encoding="utf-8"))
    Path(output_path).write_text(render_model_card(report), encoding="utf-8")
